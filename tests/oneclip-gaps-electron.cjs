const {_electron:electron,expect}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const imageHostInput=(value={})=>({enabled:true,endpoint:'https://example.com/upload',bodyMode:'binary',fieldName:'file',authMode:'bearer',tokenHeader:'X-API-Key',responsePath:'url',linkFormat:'url',timeoutSeconds:30,...value});

(async()=>{
  const output=path.resolve('work/verification');await fs.mkdir(output,{recursive:true});
  const profile=await fs.mkdtemp(path.join(output,'gaps-profile-'));
  const env={...process.env,CLIP_TEST_MODE:'1',CLIP_DATA_DIR:profile};delete env.ELECTRON_RUN_AS_NODE;
  const application=await electron.launch({args:[path.resolve('.')],env});
  try{
    const page=await application.firstWindow(),errors=[];page.on('pageerror',error=>errors.push(String(error)));
    await page.waitForSelector('#search');
    await expect(page.locator('.brand #pause-nav')).toHaveCount(1);
    await expect(page.locator('.sidebar-bottom > button')).toHaveCount(1);
    const note=await page.evaluate(()=>window.clip.applyText({mode:'save',source:'脚本处理',text:'note only'}));
    const memo=await page.evaluate(()=>window.clip.applyText({mode:'save',source:'脚本处理',text:'memo only'}));
    await expect(page.locator('.clip-row')).toHaveCount(2);
    await page.locator('#view-controls [data-view=grid]').click();
    await expect.poll(()=>page.locator('#results').getAttribute('data-view')).toBe('grid');
    const cardMetrics=await page.locator('#results').evaluate(node=>({gridAutoRows:getComputedStyle(node).gridAutoRows,gridRows:getComputedStyle(node).gridTemplateRows,resultHeight:node.getBoundingClientRect().height,rowHeight:node.querySelector('.clip-row').getBoundingClientRect().height}));
    assert(cardMetrics.rowHeight<200,JSON.stringify(cardMetrics));
    await page.screenshot({path:path.join(output,'oneclip-card-grid.png')});
    await page.locator('#card-direction').selectOption('vertical');
    await expect.poll(()=>page.locator('#results').getAttribute('data-direction')).toBe('vertical');
    await expect.poll(()=>page.locator('#results').evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' ').length)).toBe(1);
    await page.locator('#card-direction').selectOption('horizontal');
    await expect.poll(()=>page.locator('#results').evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' ').length)).toBe(1);
    await page.screenshot({path:path.join(output,'oneclip-card-horizontal.png')});
    await page.evaluate(async()=>{const api=window.clip;await api.category({name:'笔记',color:'#7b8e9c',kind:'text',contains:'note',source:'',tag:'',allowChildren:true,permanent:true});});
    const parent=(await page.evaluate(()=>window.clip.state())).categories.find(item=>item.name==='笔记');
    await page.evaluate(async id=>window.clip.category({name:'备忘',color:'#7b8e9c',kind:'text',contains:'memo',source:'',tag:'',parentId:id}),parent.id);
    await expect.poll(async()=>{const ids=await page.evaluate(id=>window.clip.search('',id),parent.id);return ids.includes(note)&&ids.includes(memo);}).toBe(true);
    await expect(page.locator('.category-nav-item.sub-category')).toHaveCount(1);
    await page.locator('#add-category').click();
    await expect(page.locator('#category-permanent')).toBeVisible();
    await expect(page.locator('#category-regex')).toBeVisible();
    await expect(page.locator('#category-parent')).toBeVisible();
    await page.keyboard.press('Escape');
    await page.evaluate(async ids=>{await window.clip.action(ids[0],'favorite');await window.clip.action(ids[1],'favorite');await window.clip.reorderFavorites(ids);},[note,memo]);
    assert.deepEqual((await page.evaluate(()=>window.clip.state())).favoriteOrder,[note,memo]);
    await page.locator('[data-page=favorites]').click();
    await expect(page.locator('.row-sort-grip')).toHaveCount(2);
    await page.locator('.row-sort-grip').first().evaluate(grip=>grip.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:new DataTransfer()})));
    await expect(page.locator('.sort-drag-ghost')).toHaveCount(0);
    await expect(page.locator('.sort-drag-proxy')).toHaveCount(1);
    await expect(page.locator('.clip-row.sort-drag-source')).toHaveCount(1);
    const stableOrder=await page.evaluate(()=>{const source=document.querySelector('.clip-row.sort-drag-source'),target=[...document.querySelectorAll('.clip-row')].find(row=>row!==source),dt=new DataTransfer(),move=()=>{const rect=target.getBoundingClientRect();target.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:dt,clientX:rect.left+rect.width/2,clientY:rect.top+rect.height/2}));return [...document.querySelectorAll('#results > .clip-row')].map(row=>row.dataset.id);},first=move(),second=move();source.querySelector('.row-sort-grip').dispatchEvent(new DragEvent('dragend',{bubbles:true,dataTransfer:dt}));return {first,second};});
    assert.deepEqual(stableOrder.first,stableOrder.second,'dragging over the same card must not oscillate');
    await expect(page.locator('.sort-drag-proxy')).toHaveCount(0);
    await page.waitForTimeout(250);
    await page.locator('.row-sort-grip').first().dragTo(page.locator('.clip-row').nth(1));
    await expect.poll(async()=>(await page.evaluate(()=>window.clip.state())).favoriteOrder[0]).toBe(memo);
    await page.evaluate(async()=>{await window.clip.snippet({title:'first',text:'a'});await window.clip.snippet({title:'second',text:'b'});});
    await page.locator('[data-page=replies]').click();
    await expect(page.locator('.row-sort-grip')).toHaveCount(2);
    const repliesBefore=(await page.evaluate(()=>window.clip.state())).snippets.map(item=>item.id);
    await page.locator('.row-sort-grip').first().dragTo(page.locator('.clip-row').nth(1));
    await expect.poll(async()=>(await page.evaluate(()=>window.clip.state())).snippets[0]?.id).toBe(repliesBefore[1]);
    await page.evaluate(value=>window.clip.configureImageHost(value),imageHostInput({token:'fixture'}));
    assert.deepEqual(await page.evaluate(()=>window.clip.imageHostState()),{...imageHostInput(),hasToken:true});
    await page.locator('[data-page=settings]').click();
    await expect(page.locator('.section-nav-group')).toHaveCount(3);
    assert.deepEqual(await page.locator('.section-nav-group').allTextContents(),['常规','交互与连接','数据']);
    assert.deepEqual((await page.locator('.section-nav button').allTextContents()).slice(0,7),['基本设置','外观','应用更新','桌面交互','记录与隐私','图床','快捷键']);
    await expect(page.locator('.section-nav button',{hasText:'图床'})).toHaveCount(1);
    await page.locator('.section-nav button',{hasText:'图床'}).click();
    await expect(page.locator('#image-host-endpoint')).toHaveValue('https://example.com/upload');
    await expect(page.locator('#image-host-body-mode')).toHaveValue('binary');
    await expect(page.locator('#image-host-test')).toBeVisible();
    await expect(page.locator('#image-host-config')).toHaveCount(0);
    await page.screenshot({path:path.join(output,'oneclip-image-host-settings.png')});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({result:'PASS',profile,screenshots:['oneclip-card-grid.png','oneclip-card-horizontal.png','oneclip-image-host-settings.png']}));
  }finally{await application.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
